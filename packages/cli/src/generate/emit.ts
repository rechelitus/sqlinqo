import type { EntityModel, GeneratedColumn, GeneratedEntity, GeneratedRelation } from './model.js';

/** A file the generator wants written, with a path relative to the output directory. */
export interface GeneratedFile {
  readonly path: string;
  readonly contents: string;
}

export interface EmitOptions {
  /**
   * Extension put on generated relative imports.
   *
   * `.js` is the default because that is what Node's ESM resolution requires of
   * a TypeScript project compiled to modules, and what a bundler tolerates
   * anyway. A project on an older resolution passes an empty string.
   */
  readonly importExtension?: string;
}

const PREAMBLE = [
  '// Generated by @sqlinqo/cli.',
  '//',
  '// This is a starting point rather than a build artefact. Rename anything that',
  '// reads badly: `table` and `column` state the physical names, so a better',
  '// property name costs nothing. Regenerating will not overwrite this file',
  '// unless it is asked to.',
].join('\n');

/** Renders the whole model: one file per entity, plus a barrel over them. */
export function emitFiles(model: EntityModel, options: EmitOptions = {}): GeneratedFile[] {
  return [
    ...model.entities.map((entity) => ({
      path: `${entity.file}.ts`,
      contents: emitEntity(entity, options),
    })),
    { path: 'index.ts', contents: emitBarrel(model, options) },
  ];
}

/** Renders one entity definition and the row type that goes with it. */
export function emitEntity(entity: GeneratedEntity, options: EmitOptions = {}): string {
  const extension = options.importExtension ?? '.js';
  const sections: string[] = [PREAMBLE, coreImport(entity), relationImports(entity, extension)];

  const body: string[] = [];
  const doc = entityDoc(entity);
  if (doc) body.push(doc);

  body.push(`export const ${entity.name} = defineEntity({`);
  body.push(`  name: ${literal(entity.name)},`);
  body.push(`  table: ${literal(entity.table)},`);
  if (entity.schema !== undefined) body.push(`  schema: ${literal(entity.schema)},`);

  body.push('  columns: {');
  for (const column of entity.columns) body.push(...emitColumn(column));
  body.push('  },');

  if (entity.relations.length > 0) {
    body.push('  relations: {');
    for (const relation of entity.relations) body.push(`    ${emitRelation(relation)},`);
    body.push('  },');
  }

  body.push('});');
  sections.push(body.join('\n'));

  // The type alias shares the constant's name on purpose: TypeScript keeps a
  // value and a type of the same name apart, and `User` is what the row wants
  // to be called in a signature.
  sections.push(`export type ${entity.name} = EntityOf<typeof ${entity.name}>;`);

  return `${sections.filter((section) => section.length > 0).join('\n\n')}\n`;
}

/**
 * Renders the barrel: every entity re-exported, and the map a context takes.
 *
 * `export *` rather than a named list, so the row type declared alongside each
 * constant comes out with it.
 */
export function emitBarrel(model: EntityModel, options: EmitOptions = {}): string {
  const extension = options.importExtension ?? '.js';
  const entities = [...model.entities].sort((a, b) => a.name.localeCompare(b.name));

  if (entities.length === 0) {
    return `${PREAMBLE}\n\n// No table in this schema could be mapped.\nexport {};\n`;
  }

  const sections = [
    PREAMBLE,
    entities.map((e) => `import { ${e.name} } from './${e.file}${extension}';`).join('\n'),
    entities.map((e) => `export * from './${e.file}${extension}';`).join('\n'),
    [
      '/**',
      ' * Every scaffolded entity, keyed by the property it is reached through.',
      ' *',
      ' * ```ts',
      ' * const db = createPostgresContext({ connectionString, entities });',
      ' * ```',
      ' */',
      'export const entities = {',
      ...entities.map((e) => `  ${e.contextKey}: ${e.name},`),
      '};',
    ].join('\n'),
  ];

  return `${sections.join('\n\n')}\n`;
}

/**
 * The import of the engine's own helpers.
 *
 * Only what the file uses is imported, since an unused import is an error under
 * a strict lint configuration and this output is meant to drop into one.
 */
function coreImport(entity: GeneratedEntity): string {
  const kinds = new Set(entity.relations.map((relation) => relation.kind));
  const values = ['defineEntity'];
  if (kinds.has('collection')) values.push('collection');
  if (kinds.has('reference')) values.push('reference');
  values.sort();

  return [
    `import { ${values.join(', ')} } from '@sqlinqo/core';`,
    "import type { EntityOf } from '@sqlinqo/core';",
  ].join('\n');
}

/**
 * Imports for the entities this one navigates to.
 *
 * Two entities that point at each other import each other, which is legal
 * precisely because a navigation names its target through a thunk: the binding
 * is not read while the module is evaluating, only when a query follows the
 * navigation. A self-reference imports nothing.
 */
function relationImports(entity: GeneratedEntity, extension: string): string {
  const targets = new Map<string, string>();
  for (const relation of entity.relations) {
    if (relation.target === entity.name) continue;
    targets.set(relation.target, relation.targetFile);
  }
  if (targets.size === 0) return '';

  return [...targets.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, file]) => `import { ${name} } from './${file}${extension}';`)
    .join('\n');
}

function entityDoc(entity: GeneratedEntity): string {
  const table = `Table \`${entity.table}\`.`;
  if (!entity.comment) return `/** ${table} */`;

  const lines = comment(entity.comment).split('\n');
  return ['/**', ...lines.map((line) => ` * ${line}`.trimEnd()), ' *', ` * ${table}`, ' */'].join(
    '\n',
  );
}

function emitColumn(column: GeneratedColumn): string[] {
  const properties = [`type: ${literal(column.type)}`];
  if (column.of) properties.push(`of: ${literal(column.of)}`);
  // The physical name is stated only where it differs, so the common case of a
  // snake_case column and its camelCase property is the only thing that shows.
  if (column.column !== column.property) properties.push(`column: ${literal(column.column)}`);
  if (column.primaryKey) properties.push('primaryKey: true');
  if (column.nullable) properties.push('nullable: true');
  if (column.generated) properties.push('generated: true');

  const lines: string[] = [];
  if (column.comment) lines.push(`    /** ${comment(column.comment).replace(/\n/g, ' ')} */`);

  const single = `    ${column.property}: { ${properties.join(', ')} },`;
  if (single.length <= 100) {
    lines.push(single);
    return lines;
  }

  // Long entries are broken the way a formatter would break them, so running
  // the output through one is a no-op rather than a diff.
  lines.push(`    ${column.property}: {`);
  for (const property of properties) lines.push(`      ${property},`);
  lines.push('    },');
  return lines;
}

function emitRelation(relation: GeneratedRelation): string {
  const options: string[] = [];
  if (relation.to) options.push(`to: ${literal(relation.to)}`);
  if (relation.kind === 'reference' && relation.optional) options.push('optional: true');

  const args = [`() => ${relation.target}`, literal(relation.from)];
  if (options.length > 0) args.push(`{ ${options.join(', ')} }`);

  return `${relation.property}: ${relation.kind}(${args.join(', ')})`;
}

/**
 * A single-quoted TypeScript string literal.
 *
 * A column name is whatever the schema author quoted into existence, so it may
 * hold a quote or a newline of its own and cannot be interpolated raw.
 */
function literal(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r');
  return `'${escaped}'`;
}

/** Makes a database comment safe to sit inside a block comment. */
function comment(text: string): string {
  return text.replace(/\*\//g, '*\\/').trim();
}
